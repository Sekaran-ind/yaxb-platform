// Embed the curated Q&A with each of the kiosk's sentence-transformers (EMBEDDING_MODELS) into
// src/data/curated_embeddings.<model>.ts. Run after editing curated_qa.json: `npm run embeddings`
// (or `npm run embeddings -- labse` for one model). The first run downloads the models (about
// 120 MB and 470 MB) into Transformers.js's cache; later runs are offline.
//
// Each vector is stored as base64 of its little-endian Float32 values, in a TypeScript module
// rather than JSON: a dynamically imported JSON module with `with { type: "json" }` fails in Vite's
// dev server (it serves JSON as JavaScript, and the browser refuses the MIME type).
// Reads the model settings from the built core (dist/), so run `npm run build` first if src changed.
import { readFileSync, writeFileSync } from "node:fs";
import { pipeline } from "@huggingface/transformers";
import { EMBEDDING_MODELS, curatedEmbeddingText, fingerprint } from "../dist/knowledge/semantic.js";

const curated = JSON.parse(readFileSync(new URL("../src/data/curated_qa.json", import.meta.url), "utf8"));
const texts = curated.map(curatedEmbeddingText);
const only = process.argv.slice(2);
const toBase64 = (vector) => Buffer.from(new Float32Array(vector).buffer).toString("base64");

for (const [key, model] of Object.entries(EMBEDDING_MODELS)) {
  if (only.length && !only.includes(key)) continue;
  const extractor = await pipeline("feature-extraction", model.id, { dtype: model.dtype });
  const vectors = (await extractor(texts, { pooling: model.pooling, normalize: true })).tolist();
  if (vectors[0]?.length !== model.dims) throw new Error(`${model.id}: expected ${model.dims} dimensions, got ${vectors[0]?.length}`);
  const items = curated.map((item, i) => ({ id: item.id, hash: fingerprint(`${model.id}\n${texts[i]}`), vector: toBase64(vectors[i]) }));
  const source = [
    "// Generated by tools/build-embeddings.mjs from curated_qa.json. Run `npm run embeddings` after editing the Q&A.",
    "// Vectors: base64 of little-endian Float32 values (decoded by ../knowledge/embeddings.ts).",
    `export default ${JSON.stringify({ model: model.id, dims: model.dims, items })};`,
    "",
  ].join("\n");
  writeFileSync(new URL(`../src/data/curated_embeddings.${key}.ts`, import.meta.url), source);
  console.log(`embeddings: ${key}: ${items.length} curated items, ${model.dims} dimensions, ${model.id}`);
}
