// Bundle content/ (skills, journeys, services, screens) into src/data/content.json as raw text.
// The core compiles and validates it (src/content/index.ts); the tests fail on any content problem.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../content/", import.meta.url));
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const list = (dir, suffix) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith(suffix))
    .sort()
    .map((f) => read(join(root, dir, f)));

const skills = readdirSync(join(root, "skills"))
  .filter((d) => statSync(join(root, "skills", d)).isDirectory())
  .sort()
  .map((name) => ({ name, markdown: read(join(root, "skills", name, "SKILL.md")) }));

const content = {
  _comment: "Generated by tools/build-content.mjs from content/. Edit the YAML and Markdown there, not this file.",
  skills,
  journeys: list("journeys", ".journey.yaml"),
  services: list("services", ".service.yaml"),
  screens: read(join(root, "screens.yaml")),
};
writeFileSync(fileURLToPath(new URL("../src/data/content.json", import.meta.url)), `${JSON.stringify(content, null, 2)}\n`);
console.log(`content: ${skills.length} skills, ${content.journeys.length} journeys, ${content.services.length} services`);
